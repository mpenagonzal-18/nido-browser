export function translate(
  source: string,
  locale: Locale,
  values: Record<string, string | number> = {},
): string {
  const message = locale === 'en' ? (ENGLISH[source] ?? source) : source;
  return message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
}

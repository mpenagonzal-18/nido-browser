export type Locale = 'es' | 'en';
export type Language = Locale | 'system';
export function resolveLocale(language: Language, systemLocale = 'es'): Locale {
  return language === 'system'
    ? systemLocale.toLowerCase().startsWith('es')
      ? 'es'
      : 'en'
    : language;
}
